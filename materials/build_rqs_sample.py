"""build_rqs_sample.py - writes assets/rqs-sample.js for learn-requirements-specs-with-phoebe.

Source: Dalpiaz, F. (2018). Requirements data sets (user stories). Mendeley Data, version 2
(2024-12-19), doi:10.17632/7zbk8zsd8y.2. Licence CC BY 4.0. 22 files, 1,721 lines.
Download every file listed by https://data.mendeley.com/public-api/datasets/7zbk8zsd8y into one
directory (check each sha256 against the API listing), then:

  python3 materials/build_rqs_sample.py <rawdir>

Changes made to the stories (CC BY 4.0 asks us to say so): folded to ASCII (curly quotes and dashes
to straight ones, other accents dropped), whitespace trimmed, empty lines dropped, then a seeded
sample of 20 stories per data set (random.Random(2018)), 440 in all, kept in file order.
The checker constants and the constructed Saffrondale presets come from rqs_reference.py.
"""
import json
import pathlib
import random
import sys
import unicodedata

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(HERE))
import rqs_reference as R  # noqa: E402

PER_SET = 20
SEED = 2018
FOLD = {"‘": "'", "’": "'", "“": '"', "”": '"', "–": "-", "—": "-",
        "…": "...", " ": " ", "﻿": ""}


def ascii_fold(s):
    for a, b in FOLD.items():
        s = s.replace(a, b)
    s = unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode("ascii")
    return " ".join(s.split())


def read_raw(rawdir):
    out = []
    for p in sorted(pathlib.Path(rawdir).glob("g*.txt")):
        lines = [ascii_fold(x) for x in p.read_text(encoding="utf-8", errors="replace").splitlines()]
        out.append((p.stem, [x for x in lines if x]))
    return out


def main(rawdir):
    sets = read_raw(rawdir)
    rng = random.Random(SEED)
    stories = []
    for di, (name, ss) in enumerate(sets):
        idx = sorted(rng.sample(range(len(ss)), min(PER_SET, len(ss))))
        stories += [[di, ss[i]] for i in idx]
    data = {
        "source": "Dalpiaz, F. (2018). Requirements data sets (user stories). Mendeley Data, v2, doi:10.17632/7zbk8zsd8y.2",
        "licence": "CC BY 4.0",
        "changes": "ASCII-folded, trimmed, seeded sample of 20 stories per data set (440 of 1,721).",
        "datasets": [n for n, _ in sets],
        "totalStories": sum(len(ss) for _, ss in sets),
        "stories": stories,
        "constants": R.CONSTANTS,
        "presets": R.PRESETS,
    }
    js = ("/* rqs-sample.js - generated by materials/build_rqs_sample.py with json.dumps; do not edit.\n"
          "   Real user stories: Dalpiaz 2018, Mendeley Data, CC BY 4.0 (changes listed in .changes).\n"
          "   Saffrondale presets are a constructed example. */\n"
          "window.RQS_SAMPLE = " + json.dumps(data, ensure_ascii=True, separators=(",", ":")) + ";\n")
    (ROOT / "assets" / "rqs-sample.js").write_text(js)
    print(len(stories), "stories from", len(sets), "sets;", data["totalStories"], "in the corpus;", len(js), "bytes")


if __name__ == "__main__":
    main(sys.argv[1])
